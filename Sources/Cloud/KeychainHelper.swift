import Foundation
import Security

/// Accès minimal au trousseau pour le jeton Authorization Cloud Key.
/// Un seul item générique, identifié par service + account — jamais dans
/// UserDefaults : c'est un secret qui donne accès au compte Zendure.
enum KeychainHelper {
    private static let service = "fr.lauriat.ZendureMonitor"
    /// Compte de l'item trousseau qui stocke le Cloud Key.
    static let cloudKeyAccount = "cloudKey"

    static func save(_ value: String, account: String) {
        let data = Data(value.utf8)
        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: account,
        ]
        // Supprimer puis recréer : SecItemUpdate a des chemins d'erreur plus
        // nombreux que delete+add pour un item aussi simple.
        SecItemDelete(query as CFDictionary)
        var attributes = query
        attributes[kSecValueData as String] = data
        SecItemAdd(attributes as CFDictionary, nil)
    }

    static func read(account: String) -> String? {
        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: account,
            kSecReturnData as String: true,
            kSecMatchLimit as String: kSecMatchLimitOne,
        ]
        var result: AnyObject?
        guard SecItemCopyMatching(query as CFDictionary, &result) == errSecSuccess,
              let data = result as? Data else { return nil }
        return String(data: data, encoding: .utf8)
    }

    static func delete(account: String) {
        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: account,
        ]
        SecItemDelete(query as CFDictionary)
    }
}
